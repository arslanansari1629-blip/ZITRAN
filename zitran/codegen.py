"""Code generation skill — HTML page builder.
Parses a natural-language spec ('build a dark blue login page called X with
a contact form') and generates a complete, polished single-file HTML page,
saved under web/generated/ and served by chat_server at /generated/<file>.
Deterministic templating = valid, working code every time.
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
ROOT = os.path.join(os.path.dirname(__file__), "..")

THEMES = {"blue": ("#2563eb", "#1e3a5f"), "red": ("#dc2626", "#7f1d1d"), "green": ("#16a34a", "#14532d"),
          "purple": ("#9333ea", "#581c87"), "orange": ("#ea580c", "#7c2d12"), "pink": ("#db2777", "#831843"),
          "dark": ("#38bdf8", "#0b1220"), "black": ("#e5e7eb", "#111827"), "teal": ("#0d9488", "#134e4a")}

def _slug(s): return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "page"

def build_html(spec):
    low = spec.lower()
    m = re.search(r"(?:called|named|titled)\s+[\"']?([A-Za-z0-9 &!.-]{2,40}?)(?:\s+with\b|\s+and\b|[\"']|$)", spec, re.I)
    title = (m.group(1).strip().strip('".') if m else None)
    if not title:
        m2 = re.search(r"(?:for|about)\s+(?:a\s+|an\s+|my\s+)?([a-z][a-z ]{2,25}?)(?:\s+page|\s+website|$)", low)
        title = (m2.group(1).strip().title() if m2 else "My Page")
    title = title[:60]
    color_name = next((c for c in THEMES if c in low), "blue")
    primary, dark = THEMES[color_name]
    dark_mode = any(k in low for k in ["dark", "black", "night"]) or color_name in ("dark", "black")
    bg, card, fg, muted = ("#0b1220", "#16263f", "#e6edf7", "#8fa3bf") if dark_mode else ("#f8fafc", "#ffffff", "#0f172a", "#64748b")
    page_kind = ("login" if "login" in low or "sign in" in low else
                 "portfolio" if "portfolio" in low else
                 "dashboard" if "dashboard" in low or "admin" in low else
                 "shop" if any(k in low for k in ["shop", "store", "ecommerce", "e-commerce"]) else
                 "restaurant" if any(k in low for k in ["restaurant", "food", "cafe", "menu"]) else "landing")
    year_note = "Generated by ZITRAN"
    sections = []
    nav = f'''<nav style="display:flex;justify-content:space-between;align-items:center;padding:16px 32px;background:{dark};color:#fff">
  <b style="font-size:20px">{title}</b>
  <span style="display:flex;gap:18px;font-size:14px"><a style="color:#fff;text-decoration:none" href="#home">Home</a><a style="color:#fff;text-decoration:none" href="#features">Features</a><a style="color:#fff;text-decoration:none" href="#about">About</a><a style="color:#fff;text-decoration:none" href="#contact">Contact</a></span></nav>'''
    hero_text = {"login": "Welcome back — sign in to continue.", "portfolio": f"Hi, I'm {title} — welcome to my portfolio.",
                 "dashboard": f"{title} — admin dashboard overview.", "shop": f"{title} — quality products, honest prices.",
                 "restaurant": f"{title} — fresh, delicious, made with love.", "landing": f"Welcome to {title} — something amazing is coming."}[page_kind]
    sections.append(f'''<header id="home" style="text-align:center;padding:72px 24px;background:linear-gradient(135deg,{primary},{dark});color:#fff">
  <h1 style="font-size:42px;margin:0 0 12px">{title}</h1><p style="font-size:18px;opacity:.92">{hero_text}</p>
  <a href="#contact" style="display:inline-block;margin-top:22px;background:#fff;color:{dark};padding:12px 28px;border-radius:999px;text-decoration:none;font-weight:700">Get Started</a></header>''')
    if page_kind == "login":
        sections.append(f'''<section style="display:flex;justify-content:center;padding:48px 20px"><form onsubmit="event.preventDefault();document.getElementById('msg').textContent='✅ Login submitted (demo)';"
  style="background:{card};padding:32px;border-radius:16px;box-shadow:0 10px 30px rgba(0,0,0,.18);width:340px;color:{fg}">
  <h2 style="margin-top:0">Sign In</h2>
  <label>Email<br><input required type="email" style="width:100%;padding:10px;margin:6px 0 14px;border-radius:8px;border:1px solid #cbd5e1"></label>
  <label>Password<br><input required type="password" style="width:100%;padding:10px;margin:6px 0 18px;border-radius:8px;border:1px solid #cbd5e1"></label>
  <button style="width:100%;background:{primary};color:#fff;border:0;padding:12px;border-radius:8px;font-weight:700;cursor:pointer">Login</button>
  <p id="msg" style="color:#16a34a"></p><small style="color:{muted}">Demo form generated by ZITRAN — connect it to your backend auth API.</small></form></section>''')
    if page_kind == "dashboard":
        cards = "".join(f'''<div style="background:{card};border-radius:14px;padding:20px;box-shadow:0 4px 14px rgba(0,0,0,.12)"><small style="color:{muted}">{label}</small><h2 style="margin:6px 0;color:{fg}">{val}</h2><small style="color:#16a34a">▲ 12% this week</small></div>'''
                        for label, val in [("Total Users", "12,480"), ("Revenue", "$48,200"), ("Orders", "1,936"), ("Alerts", "3")])
        sections.append(f'<section style="padding:36px 32px"><h2 style="color:{fg}">Overview</h2><div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(200px,1fr));gap:16px">{cards}</div></section>')
    if page_kind in ("landing", "portfolio", "shop", "restaurant"):
        feats = {"shop": [("Fast Delivery", "Orders shipped within 24 hours, tracked live."), ("Secure Payments", "Cards, UPI and wallets protected end-to-end."), ("Easy Returns", "Changed your mind? 7-day no-question returns.")],
                 "restaurant": [("Fresh Ingredients", "Sourced daily from local farms."), ("Expert Chefs", "Recipes perfected over 15 years."), ("Home Delivery", "Hot at your door in 40 minutes.")],
                 "portfolio": [("My Skills", "Web development, design and problem solving."), ("My Projects", "A selection of my best recent work."), ("Experience", "Years of building products people love.")]}.get(
                 page_kind, [("Fast & Reliable", "Built for speed, designed to last."), ("Secure by Design", "Best practices baked into every layer."), ("Loved by Users", "Simple, beautiful and easy to use.")])
        cards = "".join(f'''<div style="background:{card};border-radius:14px;padding:24px;box-shadow:0 4px 14px rgba(0,0,0,.10)"><h3 style="color:{primary};margin-top:0">{t}</h3><p style="color:{muted}">{d}</p></div>''' for t, d in feats)
        sections.append(f'<section id="features" style="padding:48px 32px"><h2 style="text-align:center;color:{fg}">Features</h2><div style="display:grid;grid-template-columns:repeat(auto-fit,minmax(230px,1fr));gap:18px;max-width:1000px;margin:24px auto">{cards}</div></section>')
    sections.append(f'''<section id="about" style="padding:40px 32px;max-width:800px;margin:auto;text-align:center"><h2 style="color:{fg}">About {title}</h2>
<p style="color:{muted};line-height:1.7">This page was generated by ZITRAN from your description: “{_escape(spec[:140])}”. Edit the text, colours and sections to make it fully yours — everything (HTML + CSS + JS) is in this single file.</p></section>''')
    if "contact" in low or page_kind != "login":
        sections.append(f'''<section id="contact" style="padding:40px 20px;display:flex;flex-direction:column;align-items:center"><h2 style="color:{fg}">Contact Us</h2>
<form onsubmit="event.preventDefault();this.reset();document.getElementById('cmsg').textContent='✅ Message sent (demo)';"
 style="background:{card};padding:28px;border-radius:16px;box-shadow:0 10px 30px rgba(0,0,0,.15);width:min(420px,92vw);color:{fg}">
 <label>Name<br><input required style="width:100%;padding:10px;margin:6px 0 12px;border-radius:8px;border:1px solid #cbd5e1"></label>
 <label>Email<br><input required type="email" style="width:100%;padding:10px;margin:6px 0 12px;border-radius:8px;border:1px solid #cbd5e1"></label>
 <label>Message<br><textarea required rows="4" style="width:100%;padding:10px;margin:6px 0 14px;border-radius:8px;border:1px solid #cbd5e1"></textarea></label>
 <button style="width:100%;background:{primary};color:#fff;border:0;padding:12px;border-radius:8px;font-weight:700;cursor:pointer">Send Message</button>
 <p id="cmsg" style="color:#16a34a"></p></form></section>''')
    sections.append(f'<footer style="text-align:center;padding:22px;background:{dark};color:#cbd5e1;font-size:13px">© 2026 {title} · {year_note} · Edit this file to customise</footer>')
    html = f'''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>body{{margin:0;font-family:'Segoe UI',system-ui,sans-serif;background:{bg};color:{fg}}} input,textarea{{box-sizing:border-box;font-size:15px}} @media(max-width:640px){{h1{{font-size:30px!important}}}}</style>
</head>
<body>
{nav}
{chr(10).join(sections)}
<script>
// Small interactive extras generated by ZITRAN
document.querySelectorAll('a[href^="#"]').forEach(a=>a.addEventListener('click',e=>{{const t=document.querySelector(a.getAttribute('href'));if(t){{e.preventDefault();t.scrollIntoView({{behavior:'smooth'}});}}}}));
console.log("{title} page loaded — generated by ZITRAN");
</script>
</body>
</html>
'''
    outdir = os.path.join(ROOT, "web", "generated"); os.makedirs(outdir, exist_ok=True)
    fname = _slug(title) + ".html"
    with open(os.path.join(outdir, fname), "w") as f: f.write(html)
    return {"file": fname, "url": f"/generated/{fname}", "title": title, "kind": page_kind,
            "theme": color_name + (" dark" if dark_mode else ""), "html": html}

def _escape(s): return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
